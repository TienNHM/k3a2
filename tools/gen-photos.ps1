# Scan photos/ and generate:
#   - src/content/photos.manifest.js   (the list of photos with sizes; imported by the site)
#   - one HTML page per room           (from tools/templates/room.html)
#
# Layout:  photos/<Room>/<Album>/NNN.jpg   (+ optional thumbs/NNN.jpg next to the photos)
# Run:     powershell -ExecutionPolicy Bypass -File tools/gen-photos.ps1
#
# Folders named avatars, thumbs or _removed are ignored. Re-run after adding, removing or deduping photos.
Add-Type -AssemblyName System.Drawing

$root = Split-Path $PSScriptRoot -Parent
$photoDir = Join-Path $root 'photos'
$manifest = Join-Path $root 'src\content\photos.manifest.js'
$template = Join-Path $PSScriptRoot 'templates\room.html'
$marker = 'generated:room'
$ext = '.jpg', '.jpeg', '.png', '.webp', '.gif'

function Get-Slug([string]$s) {
  $n = $s.Normalize([System.Text.NormalizationForm]::FormD) -replace '\p{M}', ''
  $n = $n -replace 'đ', 'd' -replace 'Đ', 'd'
  return (($n.ToLower() -replace '[^a-z0-9]+', '-').Trim('-'))
}

function Get-Size([string]$path) {
  $img = [System.Drawing.Image]::FromFile($path)
  try { return @($img.Width, $img.Height) } finally { $img.Dispose() }
}

$utf8 = New-Object System.Text.UTF8Encoding $false
$items = Get-ChildItem $photoDir -Recurse -File |
  Where-Object { $ext -contains $_.Extension.ToLower() -and $_.FullName -notmatch '\\(avatars|thumbs|_removed)\\' } |
  Sort-Object FullName |
  ForEach-Object {
    $rel = $_.FullName.Substring($root.Length + 1).Replace('\', '/')
    $parts = $rel.Split('/')   # photos / room / album / file
    if ($parts.Count -lt 4) { return }   # photos must live in photos/<room>/<album>/
    $o = [ordered]@{ src = $rel; room = $parts[1]; album = $parts[2] }
    $thumb = Join-Path (Join-Path $_.DirectoryName 'thumbs') $_.Name
    $sizeSource = $_.FullName
    if (Test-Path $thumb) { $o.thumb = $thumb.Substring($root.Length + 1).Replace('\', '/'); $sizeSource = $thumb }
    try { $wh = Get-Size $sizeSource; $o.w = $wh[0]; $o.h = $wh[1] } catch { Write-Warning "size failed: $rel" }
    $o
  }

$lines = @($items | ForEach-Object { '  ' + (ConvertTo-Json -InputObject $_ -Compress) })
$body = "// Generated by tools/gen-photos.ps1 - do not edit by hand.`nexport default [`n" + ($lines -join ",`n") + "`n];`n"
New-Item -ItemType Directory -Force (Split-Path $manifest) | Out-Null
[System.IO.File]::WriteAllText($manifest, $body, $utf8)
Write-Host "Wrote $(@($items).Count) photos to src/content/photos.manifest.js"

# Room pages
$tpl = [System.IO.File]::ReadAllText($template)
$rooms = @($items | ForEach-Object { $_.room } | Select-Object -Unique)
$slugs = @()
foreach ($r in $rooms) {
  $slug = Get-Slug $r
  $slugs += $slug
  $attr = $r.Replace('&', '&amp;').Replace('"', '&quot;').Replace('<', '&lt;')
  $html = $tpl.Replace('__ROOM__', $attr).Replace('__SLUG__', $slug)
  [System.IO.File]::WriteAllText((Join-Path $root "$slug.html"), $html, $utf8)
}
# Remove generated pages for rooms that no longer exist (hand-written pages lack the marker and are never touched).
Get-ChildItem $root -Filter *.html | Where-Object { (Get-Content $_.FullName -Raw) -match $marker -and ($slugs -notcontains $_.BaseName) } |
  ForEach-Object { Remove-Item $_.FullName; Write-Host "Removed stale page $($_.Name)" }
Write-Host "Wrote $($rooms.Count) room pages: $($slugs -join ', ')"
