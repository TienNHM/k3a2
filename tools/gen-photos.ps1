# Scan photos/ and generate photos.js (each sub-folder = one album).
# Run:  powershell -ExecutionPolicy Bypass -File tools/gen-photos.ps1
$root = Split-Path $PSScriptRoot -Parent
$photoDir = Join-Path $root 'photos'
$ext = '.jpg', '.jpeg', '.png', '.webp', '.gif'

$items = Get-ChildItem $photoDir -Recurse -File |
  Where-Object { $ext -contains $_.Extension.ToLower() -and $_.FullName -notmatch '\\avatars\\' } |
  Sort-Object FullName |
  ForEach-Object {
    $rel = $_.FullName.Substring($root.Length + 1).Replace('\', '/')
    $album = if ($_.Directory.FullName -eq $photoDir) { 'Khac' } else { $_.Directory.Name }
    [ordered]@{ src = $rel; album = $album; caption = $_.BaseName }
  }

$json = ConvertTo-Json -InputObject @($items) -Depth 3
$out = "// Auto-generated by tools/gen-photos.ps1 - do not edit by hand.`nwindow.PHOTOS = $json;`n"
[System.IO.File]::WriteAllText((Join-Path $root 'photos.js'), $out, (New-Object System.Text.UTF8Encoding $false))
Write-Host "Generated photos.js with $(@($items).Count) photos."
